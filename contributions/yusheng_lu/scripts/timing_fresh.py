#!/usr/bin/env python3
"""UCloud Q5: benchmark new validation-best tickets using SAME-trajectory fresh IMP.

Mask and full rewind state must both be generated by the freshly rerun IMP.
This script only retrains the same dense and selected ticket with epoch logging.
"""
import argparse
import csv
import json
import os
import platform
import sys
import time
from pathlib import Path

import numpy as np
import torch


def setup_repo(project):
    sys.path.insert(0, str(Path(project).resolve()))
    from lth.common import load_config, set_seed
    from lth.data.preprocess import load_dataset
    from lth.models.mlp import build_mlp
    from lth.pruning.masks import Masker
    from lth.train import make_loader, steps_per_epoch, make_scheduler, loss_fn, predict
    from lth.metrics import compute_metrics
    return (load_config, set_seed, load_dataset, build_mlp, Masker, make_loader,
            steps_per_epoch, make_scheduler, loss_fn, predict, compute_metrics)


def selected_round(archive_result):
    """Choose archived val-best nonzero ticket strictly from validation, tie earliest."""
    rr = [x for x in archive_result['records']
          if x.get('method') == 'ticket' and int(x.get('round', 0)) > 0]
    if not rr:
        raise ValueError('No nonzero ticket rounds in archived result')
    rr = sorted(rr, key=lambda x: int(x['round']))
    return max(rr, key=lambda x: float(x['metrics']['val']['accuracy']))['round']


def cuda_sync(device):
    if device.type == 'cuda':
        torch.cuda.synchronize(device)


def warmup_gpu(device, steps=40):
    """Pay one-time CUDA/optimizer startup costs BEFORE any formal timed runs.

    Uses a separate throwaway model; restores CPU/CUDA RNG afterwards. The
    actual dense initialization is reseeded independently for each pair.
    """
    if device.type != 'cuda' or steps <= 0:
        return
    cpu_rng = torch.get_rng_state().clone()
    gpu_rng = [x.clone() for x in torch.cuda.get_rng_state_all()]
    try:
        torch.manual_seed(123456789)
        x = torch.ones(128, 128, device=device)
        dummy = torch.nn.Linear(128, 128).to(device)
        opt = torch.optim.AdamW(dummy.parameters(), lr=1e-3)
        for _ in range(steps):
            loss = dummy(x).square().mean()
            opt.zero_grad(set_to_none=True)
            loss.backward()
            opt.step()
        torch.cuda.synchronize(device)
        del x, dummy, opt, loss
    finally:
        torch.set_rng_state(cpu_rng)
        torch.cuda.set_rng_state_all(gpu_rng)
        torch.cuda.empty_cache()
    print(f'GPU warm-up complete ({steps} dummy training steps).', flush=True)


def initial_seed_state(model_seed, set_seed, build_mlp, data, hp, device):
    """Original dense init follows set_seed(seed), build_mlp, model.to(device)."""
    set_seed(model_seed)
    return build_mlp(data, hp).to(device)


def measure_fit(*, data, hp, model, seed, device, kind, selected_mask, checkpoint,
                mod, on_epoch=None, cuda_prefix_step=0):
    """Replay original lth.train minibatch order and optimiser; instrument epochs.

    For sparse: exactly restore all checkpoint states (including optimizer/RNG) then
    replay DataLoader from step 0; skip first k batches without updating weights.
    For dense: start from seed-based initialization and fresh optimizer.
    Both use original fixed epoch budget, no early stopping, same data splits.
    """
    (load_config, set_seed, load_dataset, build_mlp, Masker, make_loader,
     steps_per_epoch, make_scheduler, loss_fn, predict, compute_metrics) = mod
    n_epochs = int(hp['epochs'])
    Xtr = torch.as_tensor(data.X_train, device=device)
    ytr = torch.as_tensor(data.y_train, device=device)
    loader = make_loader(len(Xtr), int(hp['batch_size']),
                         __import__('lth.common', fromlist=['make_generator']).make_generator(seed))
    total_steps = n_epochs * steps_per_epoch(len(Xtr), int(hp['batch_size']))
    opt = torch.optim.AdamW(model.parameters(), lr=hp['lr'], weight_decay=hp['weight_decay'])
    sched = make_scheduler(opt, hp, total_steps)
    crit = loss_fn(data.task_type)
    l1 = float(hp.get('l1', 0.0))
    rewind_step = 0
    masker = None
    if kind == 'ticket':
        if checkpoint is None or selected_mask is None:
            raise ValueError('Ticket requires archived mask and full rewind checkpoint')
        for key in ('model', 'opt', 'sched', 'rng', 'step'):
            if key not in checkpoint:
                raise ValueError('Archived rewind.pt is missing '+key+': full checkpoint required')
        model.load_state_dict(checkpoint['model'])
        opt.load_state_dict(checkpoint['opt'])
        sched.load_state_dict(checkpoint['sched'])
        torch.set_rng_state(checkpoint['rng']['torch'])
        if device.type == 'cuda' and checkpoint['rng'].get('cuda') is not None:
            saved = checkpoint['rng']['cuda']
            # The original CUDA_VISIBLE_DEVICES in the upstream job exposed 1 GPU.
            # Restore RNG state for this process's single visible benchmarking GPU.
            torch.cuda.set_rng_state(saved[0], device=device)
        rewind_step = int(checkpoint['step'])
        masker = Masker(model, selected_mask)
        masker.apply()
    elif kind != 'dense':
        raise ValueError(kind)
    model.train()

    # Timing excludes validation, file I/O, model construction, and data transfer
    # to GPU (Xtr/ytr allocated above). It includes optimizer and mask operations.
    history = []
    elapsed_train_s = 0.0
    prefix_train_s = 0.0
    step = 0
    for epoch in range(1, n_epochs+1):
        epoch_steps = 0
        cuda_sync(device)
        start = time.perf_counter()
        for idx in loader:
            if step < rewind_step:
                step += 1
                continue
            idx = idx.to(device)
            out = model(Xtr[idx])
            loss = crit(out, ytr[idx])
            if l1:
                loss = loss + l1 * sum(l.weight.abs().sum() for l in model.linears)
            opt.zero_grad(set_to_none=True)
            loss.backward()
            opt.step()
            if masker is not None:
                masker.apply()
            sched.step()
            step += 1
            epoch_steps += 1
            if kind == 'dense' and step == cuda_prefix_step:
                cuda_sync(device)
                prefix_train_s = elapsed_train_s + (time.perf_counter() - start)
        cuda_sync(device)
        elapsed = time.perf_counter() - start
        elapsed_train_s += elapsed
        val = compute_metrics(data.task_type, data.y_val,
                              predict(model, data.X_val, device))
        row = {
            'model': kind, 'epoch': epoch,
            'total_steps_done': step,
            'steps_executed_after_start': step - rewind_step,
            'train_seconds': elapsed,
            'cumulative_train_seconds': elapsed_train_s,
            'val_accuracy': val['accuracy'],
            'val_loss': val['loss'],
        }
        history.append(row)
        if on_epoch is not None:
            on_epoch(row)
        if epoch == 1 or epoch == n_epochs or epoch % 10 == 0:
            print(f'  {kind} epoch={epoch}/{n_epochs} step={step}/{total_steps} '
                  f'val_acc={val["accuracy"]:.4f} train_elapsed={elapsed_train_s:.2f}s', flush=True)
    # Single test evaluation after training; test data not used in model selection.
    test = compute_metrics(data.task_type, data.y_test, predict(model, data.X_test, device))
    return history, test, elapsed_train_s, prefix_train_s


def write_csv_atomic(path, rows):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix('.tmp')
    with tmp.open('w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    os.replace(tmp, path)


def write_json_atomic(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix('.tmp')
    tmp.write_text(json.dumps(data, indent=2, ensure_ascii=False, default=float))
    os.replace(tmp, path)


def first_reached(history, target, prefix_steps=0, prefix_s=0.0):
    for row in history:
        if row['val_accuracy'] >= target:
            return {'iterations': int(row['total_steps_done']),
                    'time_seconds': float(row['cumulative_train_seconds'] + prefix_s),
                    'epoch': int(row['epoch'])}
    return None


def run_pair(project, archive, out, ds, seed, mod, device, tolerance_pp=1.0):
    (load_config, set_seed, load_dataset, build_mlp, Masker, make_loader,
     steps_per_epoch, make_scheduler, loss_fn, predict, compute_metrics) = mod
    target_dir = out / ds / f'seed{seed}'
    done_file = target_dir / 'summary.json'
    if done_file.exists() and (target_dir / 'history.csv').exists():
        print(f'SKIP completed {ds} seed{seed}', flush=True)
        return
    target_dir.mkdir(parents=True, exist_ok=True)
    cfg = load_config(project / 'configs' / 'tabarena35.yaml')
    if ds not in cfg['datasets']:
        raise ValueError(f'Unsupported dataset {ds}. Check tabarena35.yaml')
    tune_file = archive / 'tuned' / f'{ds}.json'
    base = archive / 'imp_global' / ds / f'seed{seed}'
    for path in [tune_file, base/'result.json', base/'rewind.pt', base/'masks.npz']:
        if not path.exists():
            raise FileNotFoundError(f'Missing archived file {path} (check HF download)')
    hp = json.loads(tune_file.read_text())['hp']
    original = json.loads((base/'result.json').read_text())
    if int(original['seeds']['model_seed']) != seed:
        raise ValueError(f'Model seed mismatch: {ds}/{seed}')
    round_best = int(selected_round(original))
    checkpoint = torch.load(base/'rewind.pt', map_location='cpu', weights_only=False)
    k = int(checkpoint['step'])
    if k != int(original['rewind_step']):
        raise RuntimeError(f'Rewind step does not match fresh IMP record: {ds}/seed{seed}')
    if original.get('config', {}).get('controls') != []:
        raise RuntimeError('Not a Q5 freshly generated IMP archive; controls mismatch')
    data = load_dataset(cfg['datasets'][ds], cfg['split_seed'], cfg['max_train'])
    if data.task_type != 'classification':
        raise ValueError('Benchmark only supports classification')
    mask_file = np.load(base/'masks.npz')
    model_d = initial_seed_state(seed, set_seed, build_mlp, data, hp, device)
    expected_names = list(model_d.named_linears())
    masks = {}
    for name in expected_names:
        key = f'ticket/r{round_best}/{name}'
        if key not in mask_file:
            raise KeyError(f'Missing mask: {key} in {base/"masks.npz"}')
        m = torch.from_numpy(mask_file[key].astype('bool'))
        if tuple(m.shape) != tuple(model_d.named_linears()[name].weight.shape):
            raise ValueError('Mask/model shape mismatch; verify preprocessing/dependencies')
        masks[name] = m
    mask_file.close()
    print(f'RUN {ds} seed{seed} r={round_best} rewind k={k} '
          f'model={hp["depth"]}x{hp["width"]} epochs={hp["epochs"]}', flush=True)

    dense_rows, dense_test, dense_s, prefix_s = measure_fit(
        data=data, hp=hp, model=model_d, seed=seed, device=device,
        kind='dense', selected_mask=None, checkpoint=None, mod=mod, cuda_prefix_step=k)
    del model_d
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    model_t = initial_seed_state(seed, set_seed, build_mlp, data, hp, device)
    ticket_rows, ticket_test, ticket_s, _ = measure_fit(
        data=data, hp=hp, model=model_t, seed=seed, device=device,
        kind='ticket', selected_mask=masks, checkpoint=checkpoint, mod=mod)
    del model_t, checkpoint
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    # Display apples-to-apples training axes: ticket includes k prefix steps/time
    # from measured new dense reference, but NOT entire IMP search/discovery cost.
    for r in dense_rows:
        r.update(dataset=ds, seed=seed, ticket_round=round_best,
                 iterations_including_prefix=r['total_steps_done'],
                 time_including_prefix_s=r['cumulative_train_seconds'])
    for r in ticket_rows:
        r.update(dataset=ds, seed=seed, ticket_round=round_best,
                 iterations_including_prefix=r['total_steps_done'],
                 time_including_prefix_s=r['cumulative_train_seconds']+prefix_s)
    history = dense_rows + ticket_rows
    write_csv_atomic(target_dir / 'history.csv', history)
    dense_best_val = max(x['val_accuracy'] for x in dense_rows)
    target = dense_best_val - tolerance_pp/100.0
    d_target = first_reached(dense_rows, target)
    t_target = first_reached(ticket_rows, target, prefix_steps=k, prefix_s=prefix_s)
    original_dense_test = next((x['metrics']['test']['accuracy'] for x in original['records']
                                if x['method']=='dense' and x['round']==0), None)
    original_ticket_test = next((x['metrics']['test']['accuracy'] for x in original['records']
                                 if x['method']=='ticket' and x['round']==round_best), None)
    summary = {
        'dataset':ds, 'seed':seed,'ticket_round':round_best,
        'selection':'fresh IMP validation-best ticket, nonzero pruning round',
        'checkpoint_source':'same_fresh_IMP_dense_trajectory',
        'same_trajectory_mask_and_checkpoint':True,
        'rewind_step':k, 'total_epochs':int(hp['epochs']),
        'hp':hp,'target_val_accuracy':target,'accuracy_margin_pp':tolerance_pp,
        'dense_best_val_accuracy':dense_best_val,
        'dense_final_test_accuracy':dense_test['accuracy'],
        'ticket_final_test_accuracy':ticket_test['accuracy'],
        'test_accuracy_difference_pp':100*(ticket_test['accuracy']-dense_test['accuracy']),
        'comparable_final_test_accuracy':ticket_test['accuracy']>=dense_test['accuracy']-tolerance_pp/100.0,
        'dense_total_train_time_s':dense_s,
        'ticket_suffix_train_time_s':ticket_s,
        'ticket_prefix_train_time_s':prefix_s,
        'ticket_plus_prefix_total_train_time_s':ticket_s+prefix_s,
        'training_time_ratio_with_prefix':(ticket_s+prefix_s)/dense_s if dense_s else None,
        'training_time_ratio_suffix_only':ticket_s/dense_s if dense_s else None,
        'dense_time_to_target':d_target,
        'ticket_time_to_target':t_target,
        'original_dense_final_test_accuracy':original_dense_test,
        'original_ticket_final_test_accuracy':original_ticket_test,
        'gpu_name':torch.cuda.get_device_name(device) if device.type=='cuda' else 'CPU',
        'torch_version':torch.__version__, 'python_version':platform.python_version(),
        'timing_note': 'Training-loop wall-clock with CUDA synchronize. Includes mask operations and k-step prefix (estimated from replay dense); excludes validation and full IMP discovery cost. GPU warmed up before formal timing.'
    }
    # An environment/model mismatch can invalidate comparisons with the archived paper.
    for label, old_acc, new_acc in [('dense',original_dense_test,dense_test['accuracy']),
                                    ('ticket',original_ticket_test,ticket_test['accuracy'])]:
        if old_acc is not None and abs(float(old_acc)-float(new_acc)) > 0.02:
            print(f'WARNING: {ds} seed{seed} {label} final test accuracy differs from archive '
                  f'by more than 2 percentage points: archive={old_acc:.4f}, rerun={new_acc:.4f}. '
                  'Investigate environment/preprocessing before making research claims.',flush=True)
    write_json_atomic(done_file,summary)
    print(f'DONE {ds} seed{seed}: dense test {dense_test["accuracy"]:.3f}, '
          f'ticket test {ticket_test["accuracy"]:.3f}, ratio including k {summary["training_time_ratio_with_prefix"]:.3f}',flush=True)


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--project',type=Path,required=True)
    p.add_argument('--archive',type=Path,required=True)
    p.add_argument('--out',type=Path,required=True)
    p.add_argument('--datasets',nargs='+',default=['splice','SDSS17','in_vehicle_coupon','heloc','churn','MIC'])
    p.add_argument('--seeds',nargs='+',type=int,default=[42,43,44,45,46])
    p.add_argument('--accuracy-margin-pp',type=float,default=1.0)
    p.add_argument('--allow-cpu',action='store_true')
    p.add_argument('--warmup-steps',type=int,default=40)
    args=p.parse_args()
    if not args.allow_cpu and not torch.cuda.is_available():
        raise SystemExit('No CUDA GPU detected. Select UCloud GPU PyTorch app or explicitly --allow-cpu for testing.')
    if torch.cuda.is_available():
        device=torch.device('cuda:0')
        torch.backends.cuda.matmul.allow_tf32 = False
        torch.backends.cudnn.allow_tf32 = False
    else:
        device=torch.device('cpu')
    mod=setup_repo(args.project)
    warmup_gpu(device, args.warmup_steps)
    # Repo's deterministic initialization applies independently to each paired run.
    print('Q5 START device=',device,'cuda name=',torch.cuda.get_device_name(0) if device.type=='cuda' else 'n/a', flush=True)
    for ds in args.datasets:
        for seed in args.seeds:
            run_pair(args.project,args.archive,args.out,ds,seed,mod,device,args.accuracy_margin_pp)
    print('Q5 FINISHED; plotting next.',flush=True)

if __name__=='__main__':
    main()
